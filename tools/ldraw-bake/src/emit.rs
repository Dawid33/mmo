//! Write (or check) the committed outputs: the generated catalog, `parts.bin`, `colors.ron`, `ATTRIBUTION.md`.

use crate::classify::Baked;
use crate::flatten::Library;
use anyhow::{Context, Result, anyhow};
use game::stud_assets::{BAKED_PARTS_VERSION, BakedPart, BakedParts, Finish, StudColor};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use weldr::{ColorFinish, Command};

pub const CATALOG_PATH: &str = "crates/game/src/stud_catalog.rs";
pub const PARTS_BIN_PATH: &str = "assets/studs/parts.bin";
pub const COLORS_PATH: &str = "assets/studs/colors.ron";
pub const ATTRIBUTION_PATH: &str = "assets/studs/ATTRIBUTION.md";

/// Every `!COLOUR` line of `LDConfig.ldr`, in file order.
pub fn read_colors(lib: &Library) -> Result<Vec<StudColor>> {
    let path = lib.root.join("LDConfig.ldr");
    let text = std::fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
    let mut out = Vec::new();
    for line in text.lines().filter(|l| l.trim_start().starts_with("0 !COLOUR")) {
        let line = line.trim();
        let cmds = weldr::parse_raw(line.as_bytes()).map_err(|e| anyhow!("parsing `{line}`: {e:?}"))?;
        let Some(Command::Colour(c)) = cmds.into_iter().next() else {
            return Err(anyhow!("not a !COLOUR command: `{line}`"));
        };
        let alpha = c.alpha.unwrap_or(255);
        let finish = if alpha < 255 {
            Finish::Transparent
        } else {
            match c.finish {
                None => Finish::Solid,
                Some(ColorFinish::Chrome) => Finish::Chrome,
                Some(ColorFinish::Pearlescent) => Finish::Pearl,
                Some(ColorFinish::Metal | ColorFinish::MatteMetallic) => Finish::Metal,
                Some(ColorFinish::Rubber) => Finish::Rubber,
                Some(ColorFinish::Material(_)) => Finish::Other,
            }
        };
        out.push(StudColor {
            code: u16::try_from(c.code).with_context(|| format!("colour code {} > u16", c.code))?,
            name: c.name.clone(),
            rgb: [c.value.red, c.value.green, c.value.blue],
            edge: [c.edge.red, c.edge.green, c.edge.blue],
            alpha,
            finish,
        });
    }
    Ok(out)
}

fn catalog(parts: &[Baked], colors: &[StudColor]) -> String {
    let mut s = String::new();
    s.push_str("// @generated by tools/ldraw-bake (just ldraw-bake). Do not edit.\n");
    s.push_str("//! The baked LDraw part table. APPEND-ONLY: part indices are stored in sim state and orders.\n\n");
    s.push_str("use crate::stud_assets::StudPartDef;\n\n");
    s.push_str("pub const STUD_PARTS: &[StudPartDef] = &[\n");
    for p in parts {
        let d = &p.def;
        let _ = writeln!(s, "    StudPartDef {{");
        let _ = writeln!(s, "        number: {:?},", d.number);
        let _ = writeln!(s, "        name: {:?},", d.name);
        let _ = writeln!(s, "        size: {:?},", d.size);
        let _ = writeln!(s, "        studs: &{:?},", d.studs);
        if d.hull.is_empty() {
            let _ = writeln!(s, "        hull: &[],");
        } else {
            let _ = writeln!(s, "        hull: &[");
            for chunk in d.hull.chunks(4) {
                let row: Vec<String> = chunk.iter().map(|p| format!("{p:?}")).collect();
                let _ = writeln!(s, "            {},", row.join(", "));
            }
            let _ = writeln!(s, "        ],");
        }
        let _ = writeln!(s, "    }},");
    }
    s.push_str("];\n\n");
    let mut codes: Vec<u16> = colors.iter().map(|c| c.code).collect();
    codes.sort_unstable();
    codes.dedup();
    s.push_str("/// Every `!COLOUR` code of LDConfig.ldr, ascending.\n");
    s.push_str("pub const STUD_COLORS: &[u16] = &[\n");
    for chunk in codes.chunks(12) {
        let row: Vec<String> = chunk.iter().map(|c| c.to_string()).collect();
        let _ = writeln!(s, "    {},", row.join(", "));
    }
    s.push_str("];\n");
    s
}

fn attribution(parts: &[Baked]) -> String {
    let mut s = String::new();
    s.push_str("# Attribution\n\n");
    s.push_str(
        "The brick, plate and slope geometry in `parts.bin` is baked from the LDraw Parts Library\n\
         (https://www.ldraw.org), including its primitives (`p/`) and sub-parts (`parts/s/`).\n\
         The library is licensed under Creative Commons Attribution 2.0 (older files) and Creative\n\
         Commons Attribution 4.0 (newer files); see the library's `CAreadme.txt`. The colour table in\n\
         `colors.ron` is from the library's `LDConfig.ldr`. LDraw is a trademark owned and licensed\n\
         by the Estate of James Jessiman. Credit goes to the LDraw contributors named below.\n\n",
    );
    s.push_str("## Baked parts\n\n");
    for p in parts {
        let alias = if p.source != p.def.number { format!(" (file `{}.dat`)", p.source) } else { String::new() };
        let _ = writeln!(
            s,
            "- `{}`{} {} - Author: {} - {}",
            p.def.number, alias, p.def.name, p.author, p.license
        );
    }
    s
}

/// The four outputs as `(relative path, bytes)`.
pub fn outputs(lib: &Library, parts: &[Baked]) -> Result<Vec<(&'static str, Vec<u8>)>> {
    let colors = read_colors(lib)?;
    let baked = BakedParts {
        version: BAKED_PARTS_VERSION,
        parts: parts
            .iter()
            .map(|p| BakedPart { number: p.def.number.clone(), hi: p.hi.clone(), lo: p.lo.clone() })
            .collect(),
    };
    let bin = game::encode_packet(&baked).map_err(|e| anyhow!("encode parts.bin: {e}"))?;
    let ron = ron::ser::to_string_pretty(&colors, ron::ser::PrettyConfig::default())?;
    Ok(vec![
        (CATALOG_PATH, catalog(parts, &colors).into_bytes()),
        (PARTS_BIN_PATH, bin),
        (COLORS_PATH, ron.into_bytes()),
        (ATTRIBUTION_PATH, attribution(parts).into_bytes()),
    ])
}

/// Write every output under `root`, or (`check`) report the ones that differ. Returns the stale paths.
pub fn write_or_check(root: &Path, outs: &[(&'static str, Vec<u8>)], check: bool) -> Result<Vec<PathBuf>> {
    let mut stale = Vec::new();
    for (rel, bytes) in outs {
        let path = root.join(rel);
        let current = std::fs::read(&path).ok();
        if current.as_deref() == Some(bytes.as_slice()) {
            continue;
        }
        stale.push(path.clone());
        if !check {
            if let Some(dir) = path.parent() {
                std::fs::create_dir_all(dir)?;
            }
            std::fs::write(&path, bytes).with_context(|| format!("writing {}", path.display()))?;
        }
    }
    Ok(stale)
}
