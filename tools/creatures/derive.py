#!/usr/bin/env python3
"""Sources for the derived creatures, from their base creature's source:
giants (`variant_of` + `scale`) and animal people (`animal_person_of` + `size`).
Only for bases that have a source; an existing derived source is kept (hand
tweaks survive) unless --force.

python3 tools/creatures/derive.py [--force]

Giant scale: DF gives each giant a CHANGE_BODY_SIZE_PERC in the raws; the
volume ratio's cube root, damped where the base model is already drawn
exaggerated (small animals run several times their true size, so a giant
hamster is not 11× a chunky hamster): scale = ∛(perc/100) · min(1, 2 / k), k =
the base model's length over its true-volume box length; never under 1.3.
"""
import csv
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import brief  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "src")
MANIFEST = os.path.join(brief.REPO, "assets", "models", "creatures", "creatures.json")


def key(df_id):
    return df_id.lower().replace(",", "").replace(" ", "_").replace("-", "_")


def size_perc(block):
    found = re.findall(r"\[CHANGE_BODY_SIZE_PERC:(\d+)\]", block)
    return int(found[-1]) if found else None


def true_length(size_cm3):
    side = (size_cm3 / 2) ** (1 / 3) / 100 * brief.UNITS_PER_BLOCK
    return 2 * side


def main(args):
    force = "--force" in args
    rows = list(csv.DictReader(open(brief.ROSTER)))
    by_id = {r["id"]: r for r in rows}
    manifest = json.load(open(MANIFEST))
    blocks = brief.raw_blocks()
    written = 0
    for r in rows:
        if r["category"] not in ("giant", "animalperson"):
            continue
        base = r["copy_tags_from"]
        if not base or key(base) not in manifest:
            continue
        path = os.path.join(SRC, key(r["id"]) + ".toml")
        if os.path.exists(path) and not force:
            continue
        b = manifest[key(base)]
        if r["category"] == "giant":
            perc = size_perc(blocks.get(r["id"], "")) or 1000
            lo, hi = b["bounds"]
            length = max(hi[0] - lo[0], hi[2] - lo[2])
            base_size = int(by_id[base]["adult_size_cm3"] or 0) or 1000
            k = length / true_length(base_size)
            scale = max(1.3, round((perc / 100) ** (1 / 3) * min(1.0, 2.0 / k), 1))
            body = (f'# DF {r["id"]} (giant): the {by_id[base]["name"]} at {perc}% body size. Generated by\n'
                    f'# tools/creatures/derive.py; edit freely (it is kept unless --force).\n'
                    f'name = "{r["name"]}"\nvariant_of = "{key(base)}"\nstatus = "draft"\nscale = {scale}\n')
        else:
            # Between the animal and a human (the raws give no size of their own).
            size = ((int(by_id[base]["adult_size_cm3"] or 0) or 70000) + 70000) // 2
            legless = "ANIMAL_PERSON_LEGLESS" in blocks.get(r["id"], "")
            body = (f'# DF {r["id"]} (animal person): {r["description"]} Generated by\n'
                    f'# tools/creatures/derive.py; edit freely (it is kept unless --force).\n'
                    f'name = "{r["name"]}"\nanimal_person_of = "{key(base)}"\nstatus = "draft"\nsize = {size}\n'
                    + ("legless = true\n" if legless else ""))
        with open(path, "w") as f:
            f.write(body)
        written += 1
        print(os.path.relpath(path, brief.REPO))
    print(f"{written} derived sources written")


if __name__ == "__main__":
    main(sys.argv[1:])
