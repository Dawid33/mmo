-- Fulfils 0001's "R2: super_regions(owner, epoch)" note (R2b role split, Task 1).
-- Keep column-for-column in step with ../sqlite/0003_owner_epochs.sql.
-- super_regions: which host process owns a super-region, and the epoch it claimed
-- it at (the fence: a lower epoch is refused). coordinator: the one coordinator's
-- epoch and saved state. in_flight rows belong to the host that cut them.
-- Player ids are assigned by the database (identity column, below).
CREATE TABLE super_regions (
    sx BIGINT NOT NULL,
    sz BIGINT NOT NULL,
    owner BIGINT NOT NULL,
    epoch BIGINT NOT NULL,
    PRIMARY KEY (sx, sz)
);
CREATE TABLE coordinator (
    id BIGINT NOT NULL PRIMARY KEY CHECK (id = 1),
    epoch BIGINT NOT NULL,
    state BYTEA,
    saved_utc TEXT
);
ALTER TABLE in_flight ADD COLUMN host BIGINT NOT NULL DEFAULT 0;
ALTER TABLE players ALTER COLUMN player_id ADD GENERATED BY DEFAULT AS IDENTITY (MINVALUE 0 START WITH 0);
-- Existing ids stay; the sequence continues after the largest (ids start at 0 on
-- an empty table, as with SQLite's MAX+1 before).
SELECT setval(pg_get_serial_sequence('players', 'player_id'), COALESCE((SELECT MAX(player_id) + 1 FROM players), 0), false);
